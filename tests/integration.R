library(LiDAR)
cat('\nUPSTREAM INTEGRATION TEST\n')
set.seed(123)
counts<-matrix(rpois(200*100,5),200,dimnames=list(paste0('g',1:200),paste0('c',1:100)))
counts[3,seq(1,100,2)]<-0
obj<-Seurat::NormalizeData(Seurat::CreateSeuratObject(counts=counts),verbose=FALSE)
ltm<-matrix(runif(196*2),196,2,dimnames=list(paste0('g',5:200),c('g1','g2')))
lr<-data.frame(from=c('g1','g2'),to=c('g3','g4'),database='curated')
pos<-data.frame(X=rep(1:10,10)*50,Y=rep(1:10,each=10)*50,row.names=colnames(obj))
z<-CreateLiDAR(obj,assay='RNA',ligand_target_matrix=ltm,lr_network=lr,coord=pos)
stopifnot(
    identical(rownames(z@Coembedding@cell_embedding), colnames(obj)),
    setequal(rownames(z@Coembedding@gene_embedding), rownames(obj)),
    ncol(z@Coembedding@cell_embedding) == ncol(z@Coembedding@gene_embedding)
)
cat('PASS CreateLiDAR/MCA\n')
z<-ImputeExpr(z,nn=10)
cat('PASS ImputeExpr\n')
z<-BuildNetworks(z,n=c(10,15))
cat('PASS BuildNetworks\n')
z<-InferResponse(z)
cat('PASS InferResponse\n')
z<-BinLigandExpr(z,bin=50,n_bins=10)
z<-FitPropagation(z)
cat('PASS FitPropagation\n')
stopifnot(nrow(z@Diffusion@ligand_diff)>0)
z<-ComputeScores(z,mode='aggregate',ligand_list=c('g1','g2'),pval=NULL,coupling=NULL)
z<-ComputeScores(z,mode='pairwise',ligand_list=c('g1','g2'),pval=NULL,coupling=NULL)
cat('PASS aggregate and pairwise scores\n')
